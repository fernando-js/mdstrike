import { readFileSync, writeFileSync } from "node:fs";
import { teaMissions, teaSources } from "../assets/js/tea-content.js";

const bankPath = new URL("../app/tea-questions.json", import.meta.url);
const optionsPath = new URL(
  "../assets/js/tea-challenge-options.js",
  import.meta.url,
);
const bank = teaMissions.flatMap(
  ({ id: topic, title: topicTitle, questions }) =>
    questions.map(
      ({ id, point, source, prompt, correct, alternatives, explanation }) => ({
        id: `tea-${id}`,
        area: "CIR",
        kind: "original",
        reviewed: false,
        point,
        topic,
        topicTitle,
        source: teaSources[source][0],
        sourceUrl: teaSources[source][1],
        prompt,
        options: [correct, ...alternatives],
        answer: 0,
        explanation,
      }),
    ),
);

if (new Set(bank.map(({ id }) => id)).size !== bank.length)
  throw new Error("Duplicate TEA question IDs");

const topics = teaMissions.map(({ id, title, questions }) => ({
  id,
  title,
  total: questions.length,
}));
const files = [
  [bankPath, JSON.stringify(bank, null, 2) + "\n"],
  [
    optionsPath,
    "// Generated by scripts/tea-bank.mjs.\n" +
      `export const teaChallengeTopics = ${JSON.stringify(topics, null, 2)};\n`,
  ],
];
for (const [path, contents] of files) {
  if (!process.argv.includes("--check")) writeFileSync(path, contents);
  else if (readFileSync(path, "utf8") !== contents)
    throw new Error(
      `${path.pathname} is out of date. Run node scripts/tea-bank.mjs.`,
    );
}
